# ---- 7.2: Aggregated Actual vs Predicted (daily total over all test series) ----
agg = test_df.groupby("Date")[["Sales", "Predicted"]].sum()

fig, ax = plt.subplots(figsize=(14, 5))
ax.plot(agg.index, agg["Sales"],     label="Actual total",    color="steelblue", linewidth=1.8)
ax.plot(agg.index, agg["Predicted"], label="Predicted total", color="crimson",   linewidth=1.8, linestyle="--")

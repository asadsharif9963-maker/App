# ============================================================
# CELL 1: Setup, imports, and global configuration
# ============================================================

# --- Core libraries ---
import numpy as np
import pandas as pd

# --- Visualization ---
import matplotlib.pyplot as plt
import seaborn as sns

# --- ML / metrics ---
from sklearn.metrics import mean_squared_error, mean_absolute_error, mean_absolute_percentage_error, r2_score
from sklearn.preprocessing import LabelEncoder

# --- Gradient boosting ---
from xgboost import XGBRegressor

# --- Utility ---
import warnings
warnings.filterwarnings("ignore")

# --- Reproducibility ---
RANDOM_SEED = 42
np.random.seed(RANDOM_SEED)

# --- Plot styling ---
sns.set_theme(style="darkgrid", palette="husl")
plt.rcParams["figure.figsize"] = (12, 5)
plt.rcParams["axes.titlesize"] = 14
plt.rcParams["axes.labelsize"] = 12

print("Libraries loaded. Random seed:", RANDOM_SEED)
print("NumPy:", np.__version__, "| Pandas:", pd.__version__)

# ============================================================
# CELL 2: Generate a realistic synthetic retail sales dataset
# ============================================================

# ---- Global config ----
N_STORES = 5
N_ITEMS  = 10
START_DATE = "2021-01-01"
END_DATE   = "2023-12-31"

date_range = pd.date_range(START_DATE, END_DATE, freq="D")
n_days = len(date_range)

stores      = [f"S{i:02d}" for i in range(1, N_STORES + 1)]
items       = [f"I{i:02d}" for i in range(1, N_ITEMS + 1)]
categories  = ["Electronics", "Groceries", "Apparel", "Home", "Beauty"]
item_to_cat = {item: categories[(i - 1) % len(categories)] for i, item in enumerate(items)}

# ---- Holiday calendar (major US retail holidays) ----
holiday_dates = pd.to_datetime([
    "2021-01-01","2021-07-04","2021-11-25","2021-12-25",
    "2022-01-01","2022-07-04","2022-11-24","2022-12-25",
    "2023-01-01","2023-07-04","2023-11-23","2023-12-25",
])
is_holiday = date_range.isin(holiday_dates).astype(int)
holiday_boost = np.where(is_holiday == 1, 1.45, 1.0)

# ---- Shared temporal components ----
dow           = date_range.dayofweek.values                      # 0=Mon, 6=Sun
weekly_factor = np.where(dow >= 5, 1.25, 1.0)                    # weekend boost
yearly_factor = 1 + 0.25 * np.cos(2*np.pi*(date_range.dayofyear - 355)/365)  # peaks in Dec
q4_boost      = np.where(date_range.month.isin([11, 12]), 1.20, 1.0)         # Nov-Dec boost

# ---- Build dataset ----
records = []
for store in stores:
    store_effect = np.random.uniform(0.8, 1.3)                   # store size / catchment
    for item in items:
        base_demand = np.random.uniform(50, 200)                 # item popularity
        trend       = 1 + 0.0003 * np.arange(n_days)             # slow organic growth

        # Promo: ~15% of days, per store-item independently
        promo = (np.random.rand(n_days) < 0.15).astype(int)
        promo_boost = np.where(promo == 1, 1.35, 1.0)

        # Multiplicative sales model + log-normal style noise
        noise = np.random.normal(1.0, 0.08, n_days)
        sales = (base_demand * store_effect * trend
                 * yearly_factor * q4_boost
                 * weekly_factor * promo_boost * holiday_boost
                 * noise)
        sales = np.clip(np.round(sales), 0, None).astype(int)

        records.append(pd.DataFrame({
            "Date":       date_range,
            "Store_ID":   store,
            "Item_ID":    item,
            "Category":   item_to_cat[item],
            "Promotion":  promo,
            "Holiday":    is_holiday,
            "Sales":      sales,
        }))

df = pd.concat(records, ignore_index=True)
df = df.sort_values(["Date", "Store_ID", "Item_ID"]).reset_index(drop=True)

print(f"Dataset shape: {df.shape}")
display(df.head())
df.info()

# ============================================================
